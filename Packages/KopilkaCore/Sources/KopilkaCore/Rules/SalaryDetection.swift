import Foundation

/// Как среди поступлений от работодателя узнаём аванс и разовую премию (спека §5.4).
/// Одно место для импорта, главной, лимитов, аналитики и «Команд»: если пороги разойдутся,
/// периоды на экранах перестанут совпадать с правилами переводов при импорте.
public enum SalaryDetection {
    /// Поступление с 10 по 20 число — аванс, в остальные дни — зарплата.
    public static let advanceDayRange = 10...20
    /// Больше полутора обычных зарплат — разовая выплата (премия, отпускные):
    /// она не двигает границу периода и не попадает в прогноз дохода.
    public static let oneOffAboveMedianTimes: Decimal = 1.5
}
